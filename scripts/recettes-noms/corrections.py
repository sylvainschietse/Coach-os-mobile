# Fourchettes « selon source » : la quantité de la recette d'origine devient l'unité affichée
FOURCHETTES = {'tsp': 'c. à café', 'tbsp': 'c. à soupe', 'g': 'g', 'ml': 'ml', 'garlic cloves': 'gousses', 'leaves': 'feuilles', 'Thai chillies': ''}
def fourchette(original):
    m = re.match(r"^(\d+(?:\.\d+)?|1½)\s*-\s*(\d+)\s*(garlic cloves|leaves|Thai chillies|tsp|tbsp|g|ml)?", original)
    if not m: return None
    a = m.group(1).replace('.', ',').replace('1½', '1,5')
    u = FOURCHETTES.get(m.group(3) or '', '')
    return f"{a} à {m.group(2)}{(' ' + u) if u else ''}"
